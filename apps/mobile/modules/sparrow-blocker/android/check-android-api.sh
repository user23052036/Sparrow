#!/usr/bin/env bash
# Type-checks ALL the Kotlin in this module (engine, VPN filter, Expo bridge) against the real
# Android API jar, without Gradle or the Android SDK manager. This catches wrong class names,
# method signatures and nullability; it does not build an APK, merge the manifest or run anything.
#
# Needs kotlinc on PATH. The API jar comes from $ANDROID_JAR if set (e.g.
# $ANDROID_HOME/platforms/android-34/android.jar), otherwise it is downloaded once from a public
# mirror of the SDK platforms.
set -euo pipefail
cd "$(dirname "$0")"
API=34
JAR="${ANDROID_JAR:-}"
if [ -z "$JAR" ]; then
  JAR="${TMPDIR:-/tmp}/sparrow-android-$API.jar"
  if [ ! -s "$JAR" ]; then
    echo "Downloading android.jar (API $API)..."
    curl -fsSL -o "$JAR" "https://raw.githubusercontent.com/Sable/android-platforms/master/android-$API/android.jar"
  fi
fi
OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' EXIT

# R is generated by the Android build from res/; make a stand-in with the same string names,
# so a string used in code but missing from strings.xml is still an error here.
mkdir -p "$OUT/r/expo/modules/sparrowblocker"
{
  echo "package expo.modules.sparrowblocker"
  echo "object R { object string {"
  grep -o '<string name="[a-z0-9_]*"' src/main/res/values/strings.xml | sed -E 's/.*"([a-z0-9_]+)"/  const val \1: Int = 0/'
  echo "} }"
} >"$OUT/r/expo/modules/sparrowblocker/R.kt"

LOG="$OUT/log"
if ! kotlinc $(find src/main/java apicheck-stubs "$OUT/r" -name '*.kt') -cp "$JAR" -d "$OUT/all.jar" >"$LOG" 2>&1; then
  grep -v "^warning" "$LOG" || true
  echo "ANDROID API CHECK FAILED"
  exit 1
fi
grep "^src/main.*warning" "$LOG" || true
echo "ANDROID API CHECK PASSED (API $API, $(find src/main/java -name '*.kt' | wc -l | tr -d ' ') files)"
